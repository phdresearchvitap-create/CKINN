"""Harmonise RICH and NAGALA into one schema and write cohort_profile.md.

Usage: python harmonize.py RICH.xlsx NAGALA.xlsx OUT_DIR
Real data only. No imputation here: missing stays missing (NaN).
"""
import sys, pathlib
import numpy as np, pandas as pd

rich_path, nagala_path, out = sys.argv[1], sys.argv[2], pathlib.Path(sys.argv[3])
out.mkdir(parents=True, exist_ok=True)

# ---------- RICH ----------
r = pd.read_excel(rich_path)
r.columns = ['id','age','sex_raw','site','height','weight','bmi','sbp','dbp','fpg','tc','tg','hdl','ldl',
             'alt','ast','bun','ccr','fpg_final','dm_dx','censor','time_y','smoke_raw','drink_raw','famhx']
dx = r.dm_dx.fillna(0).eq(1)
assert ((r.censor == 1) == (dx | (r.fpg_final >= 7))).all(), "RICH event definition changed"
rich = pd.DataFrame({
    'cohort': 'RICH', 'id': r.id, 'site': r.site, 'age': r.age,
    'sex_male': (r.sex_raw == 1).astype(int),                      # 1 male, 2 female
    'bmi': r.bmi, 'sbp': r.sbp, 'dbp': r.dbp, 'fpg': r.fpg, 'tc': r.tc, 'tg': r.tg, 'hdl': r.hdl,
    'alt': r.alt, 'ast': r.ast,
    'smoke': r.smoke_raw.map({3: 0, 2: 1, 1: 2}),                  # 0 never, 1 former, 2 current
    'famhx': r.famhx, 'hba1c': np.nan, 'exercise': np.nan, 'waist': np.nan, 'fatty_liver': np.nan, 'ggt': np.nan,
    'time_y': r.time_y, 'event': r.censor.astype(int), 'event_dx_only': dx.astype(int)})

# ---------- NAGALA ----------
n = pd.read_excel(nagala_path)
n.columns = ['id','sex_raw','age','ethanol','fatty','bmi','wc','wc_hi','bmi25','phen','days','alt','ast','wt','exer',
             'ggt','hdl_mg','hdl','tc_mg','tc','tg_mg','tg','a1c','a1c_mm','alc','smoke_raw','fpg_mg','fpg','sbp','dbp','dm']
assert set(n.sex_raw.unique()) <= {0, 1}, "NAGALA sex coding changed"
nag = pd.DataFrame({
    'cohort': 'NAGALA', 'id': n.id, 'site': 1, 'age': n.age,
    'sex_male': n.sex_raw.astype(int),                              # ASSUMPTION: 1 = male (codebook says 1/2; data 0/1)
    'bmi': n.bmi, 'sbp': n.sbp, 'dbp': n.dbp, 'fpg': n.fpg, 'tc': n.tc, 'tg': n.tg, 'hdl': n.hdl,
    'alt': n.alt, 'ast': n.ast,
    'smoke': n.smoke_raw.map({1: 0, 2: 1, 3: 2}),
    'famhx': np.nan, 'hba1c': n.a1c, 'exercise': n.exer, 'waist': n.wc, 'fatty_liver': n.fatty, 'ggt': n.ggt,
    'time_y': n.days / 365.25, 'event': n.dm.astype(int), 'event_dx_only': np.nan})

allc = pd.concat([rich, nag], ignore_index=True)
rich.to_csv(out / 'rich_harmonized.csv', index=False)
nag.to_csv(out / 'nagala_harmonized.csv', index=False)

TIERS = {'T1 low-cost (age, sex, BMI, SBP, DBP)': ['age','sex_male','bmi','sbp','dbp'],
         'T2 = T1 + TC, TG, ALT': ['age','sex_male','bmi','sbp','dbp','tc','tg','alt'],
         'T3 = T2 + FPG': ['age','sex_male','bmi','sbp','dbp','tc','tg','alt','fpg'],
         'T4 = T3 + HDL, AST (heavy missingness in RICH)': ['age','sex_male','bmi','sbp','dbp','tc','tg','alt','fpg','hdl','ast']}

def pct(x): return f"{100*x:.1f}%"
L = ["# Cohort profile (generated by harmonize.py; do not edit by hand)\n"]
L.append("| | RICH | NAGALA |\n| --- | --- | --- |")
for lab, f in [
    ("Participants", lambda d: f"{len(d):,}"),
    ("Events", lambda d: f"{d.event.sum():,} ({pct(d.event.mean())})"),
    ("Mean follow-up, years (min–max)", lambda d: f"{d.time_y.mean():.2f} ({d.time_y.min():.2f}–{d.time_y.max():.2f})"),
    ("Person-years", lambda d: f"{d.time_y.sum():,.0f}"),
    ("Incidence per 1,000 person-years", lambda d: f"{1000*d.event.sum()/d.time_y.sum():.2f}"),
    ("Male", lambda d: pct(d.sex_male.mean())),
    ("Age, mean (min–max)", lambda d: f"{d.age.mean():.1f} ({d.age.min():.0f}–{d.age.max():.0f})"),
    ("Baseline FPG max, mmol/L", lambda d: f"{d.fpg.max():.2f}")]:
    L.append(f"| {lab} | {f(rich)} | {f(nag)} |")

L.append("\n## Missingness by harmonized variable\n\n| Variable | RICH missing | NAGALA missing |\n| --- | --- | --- |")
for c in ['age','sex_male','bmi','sbp','dbp','fpg','tc','tg','hdl','alt','ast','smoke','famhx','hba1c','exercise','waist','fatty_liver','ggt']:
    a, b = rich[c].isna().mean(), nag[c].isna().mean()
    L.append(f"| {c} | {pct(a) if a<1 else 'not collected'} | {pct(b) if b<1 else 'not collected'} |")

L.append("\n## Complete cases by predictor tier\n\n| Tier | RICH n (events) | NAGALA n (events) |\n| --- | --- | --- |")
for t, cols in TIERS.items():
    cr, cn = rich.dropna(subset=cols), nag.dropna(subset=cols)
    L.append(f"| {t} | {len(cr):,} ({cr.event.sum():,}) | {len(cn):,} ({cn.event.sum():,}) |")

L.append("\n## Horizon labelling (what share of people can be labelled at a fixed horizon)\n\n"
         "| Horizon | Cohort | Event by horizon | Event-free, followed ≥ horizon | Censored before horizon (unlabelled without weighting) |\n| --- | --- | --- | --- | --- |")
for h in (2, 3, 5):
    for nm, d in (('RICH', rich), ('NAGALA', nag)):
        ev = ((d.event == 1) & (d.time_y <= h)).sum()
        ok = ((d.event == 0) & (d.time_y >= h)).sum()
        cens = ((d.event == 0) & (d.time_y < h)).sum()
        L.append(f"| {h} y | {nm} | {ev:,} | {ok:,} | {cens:,} ({pct(cens/len(d))}) |")

L.append("\n## RICH sites\n\n| Site | n | Events | Event rate | HDL missing | Smoking missing |\n| --- | --- | --- | --- | --- | --- |")
g = rich.groupby('site').agg(n=('id','size'), ev=('event','sum'), rate=('event','mean'),
                             hdl=('hdl', lambda s: s.isna().mean()), smk=('smoke', lambda s: s.isna().mean()))
for s, row in g.iterrows():
    L.append(f"| {s} | {int(row.n):,} | {int(row.ev):,} | {pct(row.rate)} | {pct(row.hdl)} | {pct(row.smk)} |")
(out / 'cohort_profile.md').write_text("\n".join(L) + "\n")
print("\n".join(L))
