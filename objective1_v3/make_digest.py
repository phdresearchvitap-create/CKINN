def add(title, f, cols=None, d=4, query=None):
    p = EXT / f
    if not p.exists():
        out.append(f"## {title}\n\nNot available: {f} was not produced.\n")
        return
    df = pd.read_csv(p, keep_default_na=False, na_values=[""])
    if query is not None:
        df = query(df)
    out.append(f"## {title}\n")
    out.append(table(df, cols, d))

